//============================================================
// key_probe.v —— 按键探测（什么都不干，只把按键原始电平接到灯上）
//
// 用途：确定"板上的按键到底接在哪个 FPGA 球、是高有效还是低有效"。
// 之前 demo_es8388 按 S1/S2 都没反应，怀疑球号或极性记错了，
// 与其猜，不如直接把原始电平点亮来看。
//
// 第二版（2026-10-11 更新）：已确认 S1=H11、S2=H10（K6 不是按键，已移除），
// 所以现在测的两个球都是真按键，重点是确认它们各自的**极性**：
//
//   led[0] (D7/丝印LED4) = H10 (S2) 的原始电平
//   led[1] (E8/丝印LED3) = H11 (S1) 的原始电平
//
// 操作：分别**按住** S1、S2（按住不放），看对应那颗灯怎么动。
//   S1 已知是"按下=亮"（高有效）；
//   S2 若也是"按下=亮" → H10 高有效；若"按下=灭" → H10 低有效，代码要取反。
//
// 注意：第 3 个键多半是 BL616 调试器的 BOOT 键，不接 FPGA，按了没反应。
//============================================================
module key_probe(
    input  wire       key_s1,    // H11 —— 丝印 S1
    input  wire       key_s2,    // H10 —— 丝印 S2
    output wire [1:0] led        // [0]=D7, [1]=E8
);

    // 不做任何消抖/取反/同步，就是原始电平，看到什么就是什么
    assign led[0] = key_s2;      // D7 看 S2(H10)
    assign led[1] = key_s1;      // E8 看 S1(H11)

endmodule
