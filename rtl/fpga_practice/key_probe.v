//============================================================
// key_probe.v —— 按键探测（什么都不干，只把按键原始电平接到灯上）
//
// 用途：确定"板上的按键到底接在哪个 FPGA 球、是高有效还是低有效"。
// 之前 demo_es8388 按 S1/S2 都没反应，怀疑球号或极性记错了，
// 与其猜，不如直接把原始电平点亮来看。
//
// 现象：
//   led[0] (D7/丝印LED4) = K6  的原始电平
//   led[1] (E8/丝印LED3) = H11 的原始电平
//
// 操作：逐个按住板上的按键（按住不放），看哪颗灯变化、变成亮还是灭。
//   灯从灭变亮 = 该键按下时为 1（高有效）
//   灯从亮变灭 = 该键按下时为 0（低有效，有上拉）
//   灯完全不动 = 这个球号根本不是按键（记错了，要换球号）
//
// 注意：第 3 个键多半是 BL616 调试器的 BOOT 键，不接 FPGA，按了没反应。
//============================================================
module key_probe(
    input  wire       key,      // 待测按键 1（K6）
    input  wire       key2,     // 待测按键 2（H11）
    output wire [1:0] led       // [0]=D7, [1]=E8
);

    // 不做任何消抖/取反/同步，就是原始电平，看到什么就是什么
    assign led[0] = key;
    assign led[1] = key2;

endmodule
